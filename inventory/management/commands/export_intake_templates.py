"""Generate the S0 RF confirmation intake package from the models. Section 24.

``docs/design/05`` requires each intake workbook to carry *"the exact columns the eventual
import expects"*. Generating them is the only way that stays true: a hand-maintained
column list is correct on the day it is written and silently wrong after the next
migration, and the cost lands on whoever has already entered four hundred rows under the
old headings.

Run it after any change to the inventory models, and commit the result::

    python manage.py export_intake_templates

``tests/rf_confirmation`` fails if the committed files differ from what this produces, so
the drift is caught in CI rather than by an RF engineer.
"""

